/*
 * Builds the Android screen reader (scripts/android-agent/McodeAgent.java)
 * into a .dex and writes it, as base64, into
 * src/server/appdrive/android-agent.ts, which ships inside MCode - so a user
 * needs no JDK, only adb.
 *
 * Needs a JDK (javac) and an Android SDK with a platform and build-tools (d8).
 * Run with: node scripts/android-agent.mjs
 */
import fs from "node:fs"
import os from "node:os"
import path from "node:path"
import { execFileSync } from "node:child_process"
import { fileURLToPath } from "node:url"

const root = path.join(path.dirname(fileURLToPath(import.meta.url)), "..")
const source = path.join(root, "scripts", "android-agent", "McodeAgent.java")
const target = path.join(root, "src", "server", "appdrive", "android-agent.ts")

const sdk = [process.env.ANDROID_HOME, process.env.ANDROID_SDK_ROOT, process.env.LOCALAPPDATA && path.join(process.env.LOCALAPPDATA, "Android", "Sdk"), "D:\\Android\\sdk", "C:\\Android\\sdk"].find(
  (dir) => dir && fs.existsSync(path.join(dir, "platforms")),
)
if (!sdk) throw new Error("No Android SDK found; set ANDROID_HOME")
const newest = (dir) =>
  fs
    .readdirSync(dir)
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true }))
    .at(-1)
const androidJar = path.join(sdk, "platforms", newest(path.join(sdk, "platforms")), "android.jar")
const buildTools = path.join(sdk, "build-tools", newest(path.join(sdk, "build-tools")))
// d8 is run from its jar with java, not through its .bat: a shell would split a JDK path with spaces in it.
const d8Jar = path.join(buildTools, "lib", "d8.jar")
const bin = (name) => (process.env.JAVA_HOME ? path.join(process.env.JAVA_HOME, "bin", name) : name)

const work = fs.mkdtempSync(path.join(os.tmpdir(), "mcode-android-agent-"))
try {
  execFileSync(bin("javac"), ["--release", "8", "-nowarn", "-cp", androidJar, "-d", work, source], { stdio: "inherit" })
  const classes = fs.readdirSync(work).filter((name) => name.endsWith(".class")).map((name) => path.join(work, name))
  execFileSync(bin("java"), ["-cp", d8Jar, "com.android.tools.r8.D8", "--min-api", "21", "--lib", androidJar, "--output", work, ...classes], { stdio: "inherit" })
  const dex = fs.readFileSync(path.join(work, "classes.dex"))
  const lines = dex.toString("base64").match(/.{1,120}/g) ?? []
  fs.writeFileSync(
    target,
    [
      "/**",
      " * The Android screen reader the app tool runs on a device, as a .dex in",
      " * base64. Generated by scripts/android-agent.mjs from",
      " * scripts/android-agent/McodeAgent.java - edit that and run the script, not this.",
      " */",
      "export const AGENT_DEX = [",
      ...lines.map((line) => `  "${line}",`),
      '].join("")',
      "",
    ].join("\n"),
  )
  console.log(`android-agent.ts  ${dex.length} bytes of dex`)
} finally {
  fs.rmSync(work, { recursive: true, force: true })
}
