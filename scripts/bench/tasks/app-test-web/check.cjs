const assert = require("node:assert")
const fs = require("node:fs")
const Logic = require("./logic.js")
assert.strictEqual(Logic.plus(3), 4)
assert.strictEqual(Logic.minus(5), 4, "减一 should subtract one")
assert.strictEqual(Logic.reset(), 0)
assert.strictEqual(Logic.savedText("小王", "English", true), "已保存：小王，English，深色", "dark mode checked should say 深色")
assert.strictEqual(Logic.savedText("", "中文", false), "已保存：（未填昵称），中文，浅色")
const page = fs.readFileSync("index.html", "utf8")
assert.ok(/logic\.js/.test(page) && /app\.js/.test(page), "the page still loads its scripts")
console.log("check passed")
